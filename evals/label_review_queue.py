"""Build a review queue for multi-source gold labels.

Each gold question credits one labelled passage, but the docs often answer a question in
more than one place. This lists, per question, the chunks from *other* documents that the
served config ranks above the first labelled chunk (within the top 5). A human annotator
decides which of them truly answer the question; accepted ones would become extra evidence.
The script never edits `gold.jsonl` itself: changing labels after looking at a system's
misses would flatter that system.

Usage: python -m evals.label_review_queue   (writes evals/label_review_queue.md)
"""

from pathlib import Path

from rag_eval_lab.chunking import chunk_corpus
from rag_eval_lab.corpus import load_corpus
from rag_eval_lab.gold import GoldItem, load_gold, relevant_chunk_sets
from rag_eval_lab.pipeline import DEFAULT_CONFIG, build_retrievers
from rag_eval_lab.retrievers import Hit

OUTPUT = Path(__file__).resolve().parent / "label_review_queue.md"
TOP_K = 5


def review_candidates(item: GoldItem, hits: list[Hit], relevant: set[str]) -> list[Hit]:
    """Hits from other documents ranked above the first labelled chunk (or all, if none)."""
    candidates = []
    for hit in hits:
        if hit.chunk.chunk_id in relevant:
            break
        if hit.chunk.doc_path != item.doc_path:
            candidates.append(hit)
    return candidates


def main() -> None:
    docs = load_corpus()
    by_path = {d.path: d for d in docs}
    chunks = chunk_corpus(docs, DEFAULT_CONFIG.chunking)
    retriever = build_retrievers(chunks, [DEFAULT_CONFIG])[DEFAULT_CONFIG]
    lines = [
        "# Label review queue",
        "",
        f"Generated by `python -m evals.label_review_queue` with `{DEFAULT_CONFIG.name}`."
        " For each question: chunks from other documents ranked above the labelled source in the"
        " top 5. Mark each as *answers* or *does not answer*; only accepted chunks should become"
        " extra evidence quotes, and only after a second annotator agrees.",
    ]
    total = 0
    for item in load_gold():
        if not item.answerable:
            continue
        relevant = set().union(*relevant_chunk_sets(item, chunks, by_path))
        candidates = review_candidates(item, retriever.search(item.question, TOP_K), relevant)
        if not candidates:
            continue
        total += len(candidates)
        lines += [
            "",
            f"## {item.id}: {item.question}",
            "",
            f"Labelled source: `{item.doc_path}`",
            "",
        ]
        for hit in candidates:
            excerpt = " ".join(hit.chunk.text.split())[:300]
            lines.append(f"- [ ] `{hit.chunk.chunk_id}` (score {hit.score:.2f}): {excerpt}")
    lines.insert(3, "")
    lines.insert(4, f"{total} candidate chunks to review.")
    OUTPUT.write_text("\n".join(lines) + "\n")
    print(f"wrote {OUTPUT} ({total} candidates)")


if __name__ == "__main__":
    main()
